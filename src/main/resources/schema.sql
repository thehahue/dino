-- Die Standardwerte werden nur beim erstmaligen Anlegen der Tabelle eingefügt.
CREATE TABLE IF NOT EXISTS HIGHSCORE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 6) PRIMARY KEY,
    SCORE_ORDER INTEGER NOT NULL UNIQUE,
    SCORE BIGINT NOT NULL
) AS VALUES
    (1, 0, 2000),
    (2, 1, 1000),
    (3, 2, 500),
    (4, 3, 10),
    (5, 4, 5);
